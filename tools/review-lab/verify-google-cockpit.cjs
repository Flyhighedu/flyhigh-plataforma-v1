const assert = require('node:assert/strict');
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
module.exports = async function verifyGoogleCockpit(wc, until) {
  const read = value => wc.executeJavaScript(value);
  const click = label => read(`document.querySelector('[aria-label=${JSON.stringify(label)}]').click()`);
  const map = `document.querySelector('[aria-label="Mapa del ensayo de vuelo"]')`;
  const clearance = () => read(`Number(${map}.dataset.surfaceClearance)`);
  assert.ok(await clearance() >= 7.99, 'starts above known geometry');
  const saved = await read(`(async()=>{const d=await(await fetch('/api/staff/preparation?visit='+location.pathname.split('/')[3])).json(); return d.visits[0];})()`);
  const credits = await read(`(()=>{const c=document.querySelector('.cesium-widget-credits');return {text:c.innerText,height:c.parentElement.getBoundingClientRect().height,images:c.querySelectorAll('img').length}})()`);
  assert.ok(credits.text.includes('CesiumJS'));
  assert.equal(credits.images, 0, 'no oversized ion service logo for open-source renderer');
  assert.ok(credits.height <= 60, 'credits remain readable and compact');
  const telemetry = await read(`(()=>{const r=document.querySelector('[aria-label="Telemetría del ensayo"]').getBoundingClientRect();return {left:r.left,width:r.width,top:r.top,bottom:r.bottom,h:innerHeight}})()`);
  assert.ok(telemetry.top > telemetry.h * .6 && telemetry.bottom <= telemetry.h, 'landscape telemetry sits below the image');
  assert.ok(telemetry.left < 20 && telemetry.width < 250, 'compact telemetry belongs in the lower-left corner');
  assert.equal(await read(`getComputedStyle(document.querySelector('[aria-label="Telemetría del ensayo"]')).backgroundColor`), 'rgba(0, 0, 0, 0)', 'telemetry has no colored panel');
  assert.equal(await read(`${map}.dataset.initialViewReady`), 'true');
  assert.equal(await read(`${map}.dataset.movingDetail`), 'continuous');
  assert.ok(await read(`Number(${map}.dataset.tileCacheMb)`) >= 256);
  assert.equal(await read(`getComputedStyle(document.querySelector('[data-active="false"]')).opacity`), '0', 'joysticks disappear on release');

  await read(`window.__contextFetch=window.fetch;window.fetch=async(url,options)=>{if(!String(url).includes('kind=streets'))return window.__contextFetch(url,options);window.__streetQueries=(window.__streetQueries||0)+1;return Response.json({items:[{id:'street_1',name:'Calle de prueba',latitude:19.417,longitude:-102.055,source:'osm-street',geometry:[{lat:19.417,lon:-102.055},{lat:19.418,lon:-102.055}]}]});};true;`);
  await click('Mostrar calles y nombres');
  await until(() => read(`${map}.dataset.streetCount==='1'`), 'hybrid road layer');
  await read(`window.__sampleCount=0;window.__sampleBaseline=Cesium.Scene.prototype.sampleHeight;Cesium.Scene.prototype.sampleHeight=function(...args){window.__sampleCount++;return window.__sampleBaseline.apply(this,args);};true;`);
  await delay(1000);
  const samples = await read('window.__sampleCount');
  await read('Cesium.Scene.prototype.sampleHeight=window.__sampleBaseline;true;');
  assert.ok(samples < 35, 'overlay height picking is bounded, not twice per frame');
  console.log('PASS overlay height workload:', samples, 'queries in one second; quality unchanged');
  assert.equal(await read(`document.querySelectorAll('[data-street-label]').length`), 1);
  await click('Ocultar calles y nombres');
  await until(() => read(`${map}.dataset.streetCount==='0'`), 'hybrid hidden');
  await click('Mostrar calles y nombres');
  await until(() => read(`${map}.dataset.streetCount==='1'`), 'hybrid cached');
  assert.equal(await read('window.__streetQueries'), 1);
  await click('Ocultar calles y nombres');
  await read('window.fetch=window.__contextFetch;true;');
  console.log('PASS initial readiness, continuous detail, bounded memory, invisible resting sticks, hybrid toggle/cache and corner telemetry');
  const context = await read(`(async()=>{const invalid=await fetch('/api/review-lab/map-context?kind=bad&lat=19&lng=-102');const result=await fetch('/api/review-lab/map-context?kind=pois&lat=19.4169&lng=-102.0555');const data=await result.json();return {invalid:invalid.status,status:result.status,count:data.items?.length};})()`);
  assert.equal(context.invalid, 400);
  assert.equal(context.status, 200);
  assert.ok(context.count > 0, 'authenticated LAN route returns real nearby OSM places');
  console.log('PASS live radar through authenticated same-origin server:', context.count, 'places');
  const audio = await read(`(async()=>{const d=await(await fetch('/api/staff/preparation?visit='+location.pathname.split('/')[3])).json();const p=d.catalog.find(p=>p.audio_url?.includes(':54321/'));if(!p)return null;window.__audioTest=new Audio('/api/review-lab/audio?url='+encodeURIComponent(p.audio_url));await window.__audioTest.play();return {paused:window.__audioTest.paused};})()`, true);
  assert.ok(audio && !audio.paused, 'local narration can play through LAN proxy');
  await delay(500);
  assert.ok(await read('window.__audioTest.currentTime') > 0, 'audio decoder advances');
  await read('window.__audioTest.pause();true;');
  console.log('PASS actual narration playback through same-origin LAN audio endpoint');
  await click('Ajustes del ensayo');
  await until(() => read('Boolean(document.querySelector("dialog[open]"))'), 'settings drawer');
  const button = text => read(`[...document.querySelectorAll('dialog button')].find(b=>b.textContent===${JSON.stringify(text)}).click()`);
  await button('Seguridad');
  const select = (label, value) => read(`(()=>{const e=document.querySelector('select[aria-label=${JSON.stringify(label)}]');e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('change',{bubbles:true}));return e.value;})()`);
  assert.equal(await select('Altura máxima virtual', '500'), '500');
  await button('Imagen');
  await select('Calidad del relieve', 'balanced');
  await until(() => read(`${map}.dataset.quality==='balanced'`), 'balanced quality applied to same engine');
  await select('Calidad del relieve', 'high');
  const changeRange = (label, value) => read(`(()=>{const e=document.querySelector('input[aria-label=${JSON.stringify(label)}]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event('input',{bubbles:true}));e.dispatchEvent(new Event('change',{bubbles:true}));return true;})()`);
  await button('Control');
  await read(`[...document.querySelectorAll('dialog button')].find(b=>b.textContent.includes('Ajustes de ganancia y Expo')).click()`);
  assert.equal(await read(`document.querySelectorAll('input[data-tuning-field]').length`), 11);
  await changeRange('Velocidad máxima de ascenso', '8');
  await changeRange('Velocidad máxima de descenso', '2');
  await changeRange('Velocidad angular máxima', '100');
  await changeRange('Expo · Giro', '0.2');
  await changeRange('Velocidad máxima de inclinación', '10');
  await until(() => read(`document.querySelector('input[data-tuning-field="ascent"]').value==='8'`), 'separate ascent slider');
  await button('Cine');
  assert.equal(await read(`document.querySelector('input[data-tuning-field="ascent"]').value`), '3');
  await changeRange('Velocidad horizontal máxima', '2');
  await button('Sport');
  assert.equal(await read(`document.querySelector('input[data-tuning-field="horizontal"]').value`), '21');
  await button('Normal');
  assert.equal(await read(`document.querySelector('input[data-tuning-field="ascent"]').value`), '8');
  assert.equal(await read(`document.querySelector('input[data-tuning-field="descent"]').value`), '2');
  await button('Restablecer Normal');
  await button('Cine');
  assert.equal(await read(`document.querySelector('input[data-tuning-field="horizontal"]').value`), '2', 'reset only affects selected mode');
  await button('Restablecer Cine');
  await click('Cerrar ajustes');
  assert.ok(await read(`document.body.innerText.includes('Máx. 500 m')`));
  assert.equal(await read(`window.__googleCanvas===document.querySelector('.cesium-widget canvas')`), true);
  console.log('PASS compact credits, lower telemetry, 11 sliders per mode, independent profiles/reset, ceiling and quality');

  // Fault injection is isolated to this test renderer: simulate higher geometry
  // arriving while hovering. No extra external data or coordinate writes.
  await read(`window.__heightOriginal=Cesium.Scene.prototype.sampleHeight; window.__heightBoost=100; Cesium.Scene.prototype.sampleHeight=function(...args){const h=window.__heightOriginal.apply(this,args);return Number.isFinite(h)?h+window.__heightBoost:h;};true;`);
  const before = await read(`Number(${map}.dataset.cameraHeight)`);
  await until(async () => await read(`Number(${map}.dataset.cameraHeight)`) > before + 30, 'stationary terrain refinement correction');
  assert.ok(await clearance() >= 7.99);
  const high = await read(`Number(${map}.dataset.cameraHeight)`);
  await read(`Cesium.Scene.prototype.sampleHeight=window.__heightOriginal; true;`);
  await delay(700);
  assert.equal(await read(`Number(${map}.dataset.cameraHeight)`), high, 'coarse LOD must not drop the camera');
  console.log('PASS hover protection: higher streamed mesh lifts camera; lower LOD cannot sink it');

  await click('Elegir despegue en el mapa');
  await require('./verify-takeoff.cjs')(wc, until);
  await until(() => read(`!document.querySelector('[aria-label="Mapa de despegue"]')`), 'confirmed temporary takeoff');
  assert.ok(await clearance() >= 7.99);
  assert.equal(await read(`window.__googleCanvas===document.querySelector('.cesium-widget canvas')`), true);
  await click('Regresar al despegue');
  await until(() => read(`[...document.querySelectorAll('p')].find(p=>p.textContent==='DISTANCIA').nextElementSibling.textContent==='0 m'`), 'reset returns to chosen takeoff');
  const after = await read(`(async()=>{const d=await(await fetch('/api/staff/preparation?visit='+location.pathname.split('/')[3])).json(); return d.visits[0];})()`);
  assert.deepEqual(after, saved, 'temporary departure never changes the stored school/visit');
  console.log('PASS map picking, verified surface, temporary takeoff, reset, unchanged school and same WebGL context');
};
